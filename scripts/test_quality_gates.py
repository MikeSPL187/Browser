        text = "import androidx.compose.animation.AnimatedVisibility\n\nAnimatedVisibility(visible = x) { }\n"
        self.assertEqual([(line, ) for _, line, _ in gates.motion_findings_in_text(text, self.PATH)], [(1,)])

