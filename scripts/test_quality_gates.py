class SizeTest(unittest.TestCase):
    def test_growth_and_shrink_are_findings_equal_is_not(self):
        sizes = {"a.kt": 10, "b.kt": 12, "c.kt": 8}
        findings = gates.size_findings({"a.kt": 10, "b.kt": 10, "c.kt": 10}, lambda path: sizes[path.name])
        self.assertEqual([path for path, _ in findings], ["b.kt", "c.kt"])
        self.assertIn("grew from 10 to 12", findings[0][1])
        self.assertIn("--update", findings[1][1])

    def test_repository_baseline_matches_the_tree(self):
        self.assertEqual(gates.check_size(update=False), [])


