// Emit vola4.css color tokens: M3 2025 TonalSpot for UI roles, Expressive containers for the workspace aura.
import { Hct, SchemeTonalSpot, SchemeExpressive, TonalPalette, MaterialDynamicColors as M, hexFromArgb, argbFromHex, Blend } from '@material/material-color-utilities';
const seeds = { work: '#006877', anime: '#A23F2B', personal: '#5E4EB7', private: '#4B3FB5' };
const map = {
  pri: 'primary', 'on-pri': 'onPrimary', 'pri-c': 'primaryContainer', 'on-pri-c': 'onPrimaryContainer',
  sec: 'secondary', 'sec-c': 'secondaryContainer', 'on-sec-c': 'onSecondaryContainer',
  ter: 'tertiary', 'ter-c': 'tertiaryContainer', 'on-ter-c': 'onTertiaryContainer',
  sf: 'surface', 'sf-dim': 'surfaceDim', 'sf-lowest': 'surfaceContainerLowest', 'sf-low': 'surfaceContainerLow',
  'sf-c': 'surfaceContainer', 'sf-high': 'surfaceContainerHigh', 'sf-highest': 'surfaceContainerHighest',
  'on-sf': 'onSurface', 'on-sf-v': 'onSurfaceVariant', ol: 'outline', 'ol-v': 'outlineVariant',
  'inv-sf': 'inverseSurface', 'inv-on-sf': 'inverseOnSurface', err: 'error', 'err-c': 'errorContainer', 'on-err-c': 'onErrorContainer'
};
const hex = a => hexFromArgb(a).toUpperCase();
function scheme(seed, dark, contrast) {
  const src = Hct.fromInt(argbFromHex(seed));
  const s = new SchemeTonalSpot(src, dark, contrast, '2025');
  const e = new SchemeExpressive(src, dark, 0, '2025');
  const v = {};
  for (const [k, r] of Object.entries(map)) v[k] = hex(M[r].getArgb(s));
  // Aura: expressive containers give the workspace its own gradient.
  // Analogous hues keep every workspace harmonious: teal→blue, terracotta→gold, violet→pink.
  const h = src.hue;
  const at = dark ? [38, 34, 26] : [86, 84, 92];
  v['aura-1'] = hex(Hct.from(h, 44, at[0]).toInt());
  v['aura-2'] = hex(Hct.from((h + 42) % 360, 40, at[1]).toInt());
  v['aura-3'] = hex(Hct.from((h + 330) % 360, 22, at[2]).toInt());
  // Success and warning harmonized with the workspace primary.
  const pri = M.primary.getArgb(s);
  const ok = TonalPalette.fromInt(Blend.harmonize(argbFromHex('#2E7D32'), pri));
  const warn = TonalPalette.fromInt(Blend.harmonize(argbFromHex('#B26A00'), pri));
  v.ok = hex(ok.tone(dark ? 80 : 40)); v['ok-c'] = hex(ok.tone(dark ? 30 : 90)); v['on-ok-c'] = hex(ok.tone(dark ? 90 : 20));
  v.warn = hex(warn.tone(dark ? 80 : 40)); v['warn-c'] = hex(warn.tone(dark ? 30 : 90)); v['on-warn-c'] = hex(warn.tone(dark ? 90 : 20));
  return v;
}
function block(sel, v) { return `${sel} {\n` + Object.entries(v).map(([k, x]) => `  --${k}: ${x};`).join('\n') + '\n}\n'; }
let css = '/* Generated by tools/gencss.mjs from workspace seeds (Material color utilities, spec 2025). Do not edit by hand. */\n';
for (const [w, seed] of Object.entries(seeds)) {
  if (w !== 'private') css += block(`.w-${w}.t-light`, scheme(seed, false, 0));
  // Dark theme is always pure black (owner decision): the surface ladder starts at #000000.
  const d = scheme(seed, true, 0);
  css += block(`.w-${w}.t-dark`, { ...d, sf: '#000000', 'sf-dim': '#000000', 'sf-lowest': '#000000' });
  if (w !== 'private') css += block(`.w-${w}.t-light.hc`, scheme(seed, false, 1));
}
process.stdout.write(css);
